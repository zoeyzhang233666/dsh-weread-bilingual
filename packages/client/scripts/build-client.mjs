import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const PLUGIN = dirname(dirname(fileURLToPath(import.meta.url)))
const OUTPUT = join(PLUGIN, 'client.js')
const PLATFORM = ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives']

const result = await build({
  absWorkingDir: PLUGIN,
  entryPoints: ['src/index.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: PLATFORM,
  charset: 'utf8',
  write: false,
  logLevel: 'silent',
  jsx: 'automatic',
  loader: { '.js': 'jsx' },
})

if (result.warnings.length) {
  throw new Error(result.warnings.map(warning => warning.text).join('\n'))
}

const text = [
  '// Generated by scripts/build-client.mjs. Do not edit by hand.',
  'window.__ModuleLoader__.load({',
  "  id: 'dsh-weread-bilingual-client',",
  '  factory: (require) => {',
  'const module = { exports: {} }',
  result.outputFiles[0].text.trimEnd(),
  "return Object.defineProperty({ ...module.exports }, Symbol.toStringTag, { value: 'Module' })",
  '  },',
  '})',
  '',
].join('\n')

writeFileSync(OUTPUT, text)
console.log(`wrote ${OUTPUT}`)
